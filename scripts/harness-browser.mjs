/** Windows Chrome against the isolated WSL Harness. Auth token is never logged. */
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/Denni/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const [url,out]=process.argv.slice(2);
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
try {
  const page=await browser.newPage({viewport:{width:1440,height:980}});
  const failures=[];page.on('pageerror',e=>failures.push(e.message));
  await page.goto(url,{waitUntil:'domcontentloaded',timeout:60000});
  const settings=page.locator('[data-slot="sidebar.settings"]');
  await settings.waitFor({timeout:60000});
  const welcome=page.getByRole('button',{name:/^(继续|Continue)$/});
  await welcome.waitFor({state:'visible',timeout:15000});
  await welcome.click();
  await welcome.waitFor({state:'hidden'});
  const later=page.getByRole('button',{name:/^(稍后配置|Configure later)$/});
  await later.waitFor({state:'visible',timeout:15000});
  await later.click();
  await later.waitFor({state:'hidden'});
  const launcher=page.getByRole('button',{name:'Token / 费用',exact:true});
  await launcher.waitFor();
  assert.ok(await page.locator('#dsh-bill-visualization-launcher').evaluate(e=>!!e.nextElementSibling?.querySelector('[data-slot="sidebar.settings"]')));
  const trigger=settings.locator('button').first();
  const left=await launcher.boundingBox(), below=await trigger.boundingBox();
  assert.ok(left.y+left.height<=below.y+1,'launcher must sit above Settings');
  await page.screenshot({path:join(out,'sidebar-real-harness.png'),fullPage:true});
  await launcher.click();
  const frame=page.frameLocator('#dsh-bill-visualization-modal iframe');
  await frame.locator('#connection').filter({hasText:'已连接本机'}).waitFor();
  assert.equal(await frame.locator('#total-tokens').innerText(),'180');
  await frame.locator('[data-tab="rates"]').click();
  await frame.locator('#import-official').click();
  await frame.locator('#rate-rows tr').nth(3).waitFor();
  await page.screenshot({path:join(out,'official-prices-real-harness.png'),fullPage:true});
  await frame.locator('#provider').press('Escape');
  assert.equal(await page.locator('dialog').evaluate(e=>e.open),false);
  await page.getByRole('button',{name:/^(收起侧边栏|Collapse sidebar)$/}).click();
  await page.waitForFunction(()=>document.querySelector('#dsh-bill-visualization-launcher')?.hasAttribute('data-collapsed'));
  assert.ok((await launcher.boundingBox()).width<=38);
  await page.getByRole('button',{name:/^(打开侧边栏|Open sidebar)$/}).click();
  await page.waitForFunction(()=>!document.querySelector('#dsh-bill-visualization-launcher')?.hasAttribute('data-collapsed'));
  assert.equal(await page.locator('#dsh-bill-visualization-launcher').count(),1);
  const relevant=failures.filter(t=>/dsh-bill-visualization|pricing\.js/.test(t));assert.deepEqual(relevant,[]);
  const result={passed:true,checks:['real sidebar DOM slot','above settings geometry','authenticated iframe','official preset save','Escape inside iframe','real sidebar collapse/expand'],unrelatedHostPageErrors:failures.filter(t=>!relevant.includes(t))};
  await writeFile(join(out,'harness-browser-results.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
} finally {await browser.close();}
